const BY_ID = new Map(EVENT_TYPES.map((e) => [e.id, e]));

export function eventTypeById(id: string): EventTypeDef | undefined {
  return BY_ID.get(id);
}

/** Disposal event ids that feed the Garbage Record Book (manual §3.17). */
export const DISPOSAL_EVENT_IDS = [
  'disposal_incineration',
  'disposal_ashore',
  'disposal_overboard',
  'disposal_barge',
];

/** Events that are "in sequence" given the current voyage state. */
export function eventsInSequence(state: VoyageState): EventTypeDef[] {
  return EVENT_TYPES.filter(
    (e) => e.category !== 'Voyage' || (e.allowedAfter?.includes(state) ?? false),
  );
}
